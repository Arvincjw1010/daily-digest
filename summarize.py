"""AI 整理模块：用 DeepSeek 对原始内容进行去重、排序和摘要"""

from openai import OpenAI

DEEPSEEK_BASE_URL = "https://api.deepseek.com"


def _build_prompt(interest_name: str, results: list[dict]) -> str:
    items_text = ""
    for i, r in enumerate(results, 1):
        items_text += (
            f"[{i}] {r['title']}\n"
            f"   {r['content'][:300]}\n"
            f"   原文链接: {r['url']}\n\n"
        )

    # 根据兴趣类型定制 prompt
    if "产品" in interest_name:
        angle = """你是一个关注大模型产品动态的分析师。下面是一组今天的 AI 行业原始信息。

你的任务是筛选和整理：
1. **只保留产品相关的信息**：新功能发布、模型升级、API 变更、定价调整、产品下线/合并
2. **扔掉无关内容**：纯学术论文、企业融资新闻（除非涉及产品）、泛泛的行业预测
3. **每条写法的要求**：
   - 标题：一句话说清楚「谁 + 做了什么 + 为什么值得关注」
   - 摘要 2-3 句：这条更新对我有什么影响？我需要知道什么？
   - 末尾附带原文链接（Markdown 格式）
4. **按重要程度排序**：ChatGPT/Claude/Gemini 等主流产品优先，小众工具放后面
5. **去重合并**：同一事件多家报道合并为一条

输出格式（严格 Markdown）：
- **OpenAI 发布 GPT-5 API，价格下调 50%**：今日起 GPT-5 的 API 调用费用减半，同时新增了函数调用的流式支持... [来源](https://...)
- **Claude 推出团队协作空间**：Anthropic 为 Claude 企业版增加了共享工作区功能... [来源](https://...)"""
    elif "国内" in interest_name:
        angle = """你是一个关注中国 AI 行业动态的观察者。下面是一组今天的中文 AI 资讯原始信息。

你的任务是筛选和整理：
1. **值得关注的内容类型**：
   - 国产大模型发布/更新（DeepSeek、文心一言、通义千问、豆包、Kimi、智谱、百川等）
   - AI 应用落地案例（国内公司的实际部署和使用场景）
   - 行业重要动态（大厂人才流动、芯片进展、关键人物的观点和预警）
   - 开源项目和技术突破（国内的 AI 开源框架、工具）
   - AI 商业化案例（AI 赚钱/变现的实际案例）
2. **扔掉的内容**：
   - 明显与 AI 无关的（数码产品评测、娱乐影视推荐、macOS 技巧等）
   - 纯软文/广告/付费推广
   - 活动预告/直播预告
3. **每条写法**：
   - 标题：谁 + 做了什么 + 为什么值得关注
   - 摘要 2-3 句中文：核心信息和影响
   - 末尾附带原文链接
4. **按重要性和信息密度排序**
5. **去重合并**：同一事件多家报道合并为一条

⚠️ 重要：只要内容涉及 AI，就可以保留。不要因为标题夸张（如"叛逃""吹哨""杀到"）就跳过——国内科技媒体的标题风格如此，正文往往有实质信息。与 AI 无关的内容直接跳过。

输出格式（严格 Markdown）：
- **DeepSeek 发布 V3 模型，推理成本再降 50%**：DeepSeek 今日更新了 V3 版本，API 价格下调，同时在多轮对话能力上有显著提升... [来源](https://...)
- **OpenAI 芯片负责人跳槽 Anthropic，量产前夜生变**：负责 OpenAI 自研芯片的核心高管转投 Anthropic，可能影响 OpenAI 的芯片量产计划和两家公司的算力竞争格局... [来源](https://...)"""
    elif "吃喝" in interest_name:
        angle = """你是一个广州本地的美食和生活方式编辑。下面是一组今天的吃喝玩乐/生活方式原始信息。

⚠️ 重点：只关注广州的内容。佛山、顺德可以算上。其他城市的内容除非特别惊艳，否则直接跳过。

你的任务是筛选和整理：
1. **值得推荐的内容类型**：
   - 广州新店/探店：餐厅、咖啡馆、酒吧、甜品店、面包店，最好说清楚在哪个区
   - 广州周末好去处：Citywalk路线、展览、市集、周边短途（佛山/顺德/清远）
   - 广州地道美食：老字号、大排档、隐藏小店、早茶、糖水、牛杂、肠粉、煲仔饭、啫啫煲
   - 好物种草：实用好物、数码新品、家居好物，有真实体验感
   - 广州生活省钱攻略/避坑指南
2. **扔掉的内容**：
   - 非广州/佛山/顺德的内容
   - 纯软文/广告（一眼就能看出是付费推广）
   - AI/科技类（另一个板块会处理）
   - 纯优惠券/促销信息
3. **每条写法**：
   - 标题：店名或地方 + 一句话亮点 + 区/位置
   - 摘要 2-3 句：好在哪？人均多少？怎么去？适合什么时候？
   - 末尾附带原文链接
4. **按实用性和新鲜度排序**：今天/这周就能去的排前面

输出格式（严格 Markdown）：
- **🍜 体育西新开云南小馆，米线每日现做人均60**：藏在六运小区里，主打云南家常菜。米线每天现做，汤底 8 小时熬制。地铁 3 号线体育西路站 B 口出，适合工作日午餐或周末 brunch... [来源](https://...)
- **☕ 东山口日式手冲咖啡馆，藏在老洋楼里**：店主从京都学艺回来，用自家烘焙豆子。空间不大但安静，适合一个人发呆看书。周末下午人少，坐地铁 1 号线东山口站... [来源](https://...)"""
    else:
        angle = """你是一个关注 AI 创意应用和有趣工具的观察者。下面是一组今天与 AI 相关的原始信息。

你的任务是：
1. **只保留新奇好玩的内容**：新出的 AI 工具、让人眼前一亮的使用案例、有趣的实验和 demo、社区里的热门讨论
2. **扔掉**：干巴巴的产品公告、融资新闻、学术论文、重复报道
3. **每条写法**：
   - 标题：名字或玩法 + 一句话亮点
   - 摘要 2-3 句：这个工具/项目做了什么？为什么有趣？我可以怎么试？
   - 末尾附带原文链接（Markdown 格式）
4. **按趣味性和实用性排序**：让人想立刻去试的排前面
5. **去重合并**：同一项目被多方讨论的合并为一条

输出格式（严格 Markdown）：
- **Open-Sora 2.0 发布，消费级显卡可跑视频生成**：清华大学团队开源的视频生成模型更新，RTX 4090 即可运行... [来源](https://...)
- **开发者用 Claude 写了一个自动修 Bug 的 GitHub Action**：一位独立开发者分享了用 Claude API 搭建的自动修复工具... [来源](https://...)"""

    return f"""{angle}

⚠️ 重要：不相关的内容直接跳过，宁可少而精。如果所有原始信息都不相关，回复「今日无值得关注的内容」即可，不要硬凑。

原始搜索结果：
{items_text}
请输出整理后的摘要："""


def summarize_interest(
    interest_name: str,
    results: list[dict],
    api_key: str,
    model: str = "deepseek-chat",
) -> str:
    """调用 DeepSeek API 整理摘要，返回 Markdown 文本。"""
    if not results:
        return ""

    client = OpenAI(api_key=api_key, base_url=DEEPSEEK_BASE_URL)
    prompt = _build_prompt(interest_name, results)

    try:
        resp = client.chat.completions.create(
            model=model,
            messages=[{"role": "user", "content": prompt}],
            temperature=0.3,
            max_tokens=4096,
        )
        return resp.choices[0].message.content or ""
    except Exception as e:
        print(f"  [ERROR] DeepSeek API 调用失败: {e}")
        return ""
